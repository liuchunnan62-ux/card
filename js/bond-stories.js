  const BondStories = {
    PERSONAL_LEVEL,
    CHAPTER_THRESHOLDS,
    RACE_CHAPTERS,
    voice(chapter, level) {
      const lines = VOICES[chapter];
      return lines && level >= 1 ? lines[Math.min(level, lines.length) - 1] : "";
    },
    personal(name) { return PERSONAL[name] || ""; },
    personalUnlocked(key) { return CF.Restaurant.bondLevel(key) >= PERSONAL_LEVEL; },
    // 本关全部在押首领的好感等级总和：决定族群往事解锁到第几章。
    chapterBondTotal(chapter) {
      return CF.Adventure.prisonRoster().filter(prisoner => prisoner.chapter === chapter && prisoner.cardId).reduce((sum, prisoner) => sum + CF.Restaurant.bondLevel(prisoner.key), 0);
    },
    unlockedChapters(chapter) {
      const total = this.chapterBondTotal(chapter);
      return CHAPTER_THRESHOLDS.filter(threshold => total >= threshold).length;
    },
    // 当前已解锁的全部剧情条目数，用于在投喂后提示“解锁了新的往事”。
    unlockedCount() {
      const personal = CF.Adventure.prisonRoster().filter(prisoner => prisoner.cardId && PERSONAL[prisoner.name] && this.personalUnlocked(prisoner.key)).length;
      return personal + Object.keys(RACE_CHAPTERS).reduce((sum, chapter) => sum + this.unlockedChapters(Number(chapter)), 0);
    }
  };

  CF.BondStories = BondStories;
  CF.BOND_PERSONAL_STORIES = PERSONAL;
